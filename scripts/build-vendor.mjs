/**
 * Builds the vendored offline voice runtime.
 *
 * The extension itself has no build step: this script only regenerates the
 * committed bundle in vendor/mespeak/ from the npm packages. Run it when
 * upgrading mespeak:
 *
 *   npm run build:vendor
 */
import { build } from 'esbuild';
import fs from 'node:fs/promises';
import fsSync from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const PACKAGE = path.join(ROOT, 'node_modules/mespeak');
const OUT = path.join(ROOT, 'vendor/mespeak');

await fs.mkdir(path.join(OUT, 'voices/en'), { recursive: true });

await build({
  entryPoints: [path.join(PACKAGE, 'src/index.js')],
  bundle: true,
  format: 'iife',
  globalName: 'meSpeakLib',
  minify: true,
  legalComments: 'none',
  outfile: path.join(OUT, 'mespeak.bundle.js'),
  banner: {
    js: '/* meSpeak 1.9.6 (based on eSpeak, GPL). Bundled for offline use. See vendor/mespeak/LICENSE. */',
  },
});

await fs.copyFile(
  path.join(PACKAGE, 'src/mespeak_config.json'),
  path.join(OUT, 'mespeak_config.json'),
);
await fs.copyFile(
  path.join(PACKAGE, 'voices/en/en-us.json'),
  path.join(OUT, 'voices/en/en-us.json'),
);

// Keep the committed GPL text when regenerating on systems without the
// common-licenses copy.
const licenseSource = ['/usr/share/common-licenses/GPL-3', path.join(OUT, 'LICENSE')]
  .find((candidate) => fsSync.existsSync(candidate));
if (licenseSource) await fs.copyFile(licenseSource, path.join(OUT, 'LICENSE'));

await fs.writeFile(
  path.join(OUT, 'README.md'),
  [
    '# Bundled offline voice',
    '',
    'This folder contains [meSpeak](http://www.masswerk.at/mespeak/) 1.9.6, a',
    'JavaScript port of eSpeak, plus its configuration and the US English voice.',
    'It is bundled so the extension can speak when the browser reports no system',
    'voices. Synthesis happens locally in an offscreen extension document and',
    'the resulting PCM is played with Web Audio. Nothing is downloaded at read',
    'time.',
    '',
    'The bundle is generated by `npm run build:vendor` from the `mespeak` npm',
    'package. meSpeak and eSpeak are licensed under the GNU GPL; see LICENSE.',
    '',
  ].join('\n'),
);

console.log('Vendored meSpeak into', path.relative(ROOT, OUT));
